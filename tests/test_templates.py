"""Tests for template rendering functions."""

from __future__ import annotations

from pathlib import Path

import pytest

from ai_scaffold.providers import AI_PROVIDERS
from ai_scaffold.scaffold import ScaffoldConfig
from ai_scaffold.templates import (
    _render_docker,
    _render_env_example,
    render_all,
)


def make_config(tmp_path: Path, **kwargs) -> ScaffoldConfig:
    defaults = dict(
        project_name="test-app",
        ai_provider="openai",
        auth_provider="clerk",
        db_provider="sqlite",
        payment_provider="stripe",
        monitoring=False,
        docker=True,
        ci=False,
        output_dir=tmp_path,
    )
    defaults.update(kwargs)
    return ScaffoldConfig(**defaults)


# ---------------------------------------------------------------------------
# _render_env_example
# ---------------------------------------------------------------------------

class TestRenderEnvExample:
    def test_contains_header_comment(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "Auto-generated by ai-scaffold" in content

    def test_contains_app_env_var(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "APP_ENV=development" in content
        assert "SECRET_KEY=change-me-in-production" in content

    def test_contains_ai_provider_key(self, tmp_path):
        config = make_config(tmp_path, ai_provider="openai")
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "OPENAI_API_KEY=" in content

    def test_contains_anthropic_key(self, tmp_path):
        config = make_config(tmp_path, ai_provider="anthropic")
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "ANTHROPIC_API_KEY=" in content

    def test_contains_gemini_key(self, tmp_path):
        config = make_config(tmp_path, ai_provider="gemini")
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "GOOGLE_API_KEY=" in content

    def test_stripe_vars_present_when_payment_is_stripe(self, tmp_path):
        config = make_config(tmp_path, payment_provider="stripe")
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "STRIPE_SECRET_KEY=" in content

    def test_payment_section_absent_when_none(self, tmp_path):
        config = make_config(tmp_path, payment_provider="none")
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "STRIPE_SECRET_KEY" not in content
        assert "LEMONSQUEEZY" not in content

    def test_sentry_dsn_present_when_monitoring_enabled(self, tmp_path):
        config = make_config(tmp_path, monitoring=True)
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "SENTRY_DSN=" in content

    def test_sentry_dsn_absent_when_monitoring_disabled(self, tmp_path):
        config = make_config(tmp_path, monitoring=False)
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "SENTRY_DSN" not in content

    def test_returns_single_path(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_env_example(config, tmp_path)
        assert len(paths) == 1
        assert paths[0].name == ".env.example"

    def test_file_is_written_to_disk(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_env_example(config, tmp_path)
        assert paths[0].exists()

    def test_model_default_included(self, tmp_path):
        config = make_config(tmp_path, ai_provider="openai")
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        assert "AI_MODEL=gpt-4o" in content


