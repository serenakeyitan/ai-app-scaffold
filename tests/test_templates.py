class TestRenderDocker:
    def test_creates_dockerfile(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_docker(config, tmp_path)
        names = [p.name for p in paths]
        assert "Dockerfile" in names

    def test_creates_compose_file(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_docker(config, tmp_path)
        names = [p.name for p in paths]
        assert "docker-compose.yml" in names

    def test_dockerfile_uses_python_slim(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_docker(config, tmp_path)
        dockerfile = next(p for p in paths if p.name == "Dockerfile")
        content = dockerfile.read_text()
        assert "python:3.12-slim" in content

    def test_dockerfile_exposes_port_8000(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_docker(config, tmp_path)
        dockerfile = next(p for p in paths if p.name == "Dockerfile")
        content = dockerfile.read_text()
        assert "EXPOSE 8000" in content

    def test_compose_references_project_name(self, tmp_path):
        config = make_config(tmp_path, project_name="my-unique-app")
        paths = _render_docker(config, tmp_path)
        compose = next(p for p in paths if p.name == "docker-compose.yml")
        content = compose.read_text()
        assert "my-unique-app" in content

    def test_dockerfile_has_uvicorn_cmd(self, tmp_path):
        config = make_config(tmp_path)
        paths = _render_docker(config, tmp_path)
        dockerfile = next(p for p in paths if p.name == "Dockerfile")
        content = dockerfile.read_text()
        assert "uvicorn" in content


