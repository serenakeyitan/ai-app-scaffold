# All AI provider templates render without error
# ---------------------------------------------------------------------------

class TestAllAIProvidersRender:
    @pytest.mark.parametrize("ai_provider", list(AI_PROVIDERS.keys()))
    def test_render_all_succeeds(self, tmp_path, ai_provider):
        config = make_config(
            tmp_path,
            ai_provider=ai_provider,
            docker=True,
            ci=True,
            monitoring=True,
        )
        project_dir = tmp_path / config.project_name
        project_dir.mkdir(parents=True, exist_ok=True)
        files = render_all(config, project_dir)
        assert len(files) > 0

    @pytest.mark.parametrize("ai_provider", list(AI_PROVIDERS.keys()))
    def test_env_example_has_ai_section(self, tmp_path, ai_provider):
        config = make_config(tmp_path, ai_provider=ai_provider)
        paths = _render_env_example(config, tmp_path)
        content = paths[0].read_text()
        # Each AI provider must mention the provider name in a comment
        assert f"# AI — {ai_provider}" in content
