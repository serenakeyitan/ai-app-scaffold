def _render_docker(config: ScaffoldConfig, root: Path) -> list[Path]:
    files: list[Path] = []

    dockerfile = """\
FROM python:3.12-slim

WORKDIR /app

# Install dependencies
COPY pyproject.toml .
RUN pip install --no-cache-dir -e .

# Copy source
COPY app/ ./app/

EXPOSE 8000

CMD ["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "8000"]
"""
    files.append(_write(root / "Dockerfile", dockerfile))

    compose = f"""\
version: "3.9"

services:
  api:
    build: .
    ports:
      - "8000:8000"
    env_file:
      - .env
    depends_on:
      - db
    restart: unless-stopped

  db:
    image: postgres:16-alpine
    environment:
      POSTGRES_USER: app
      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD:-secret}}
      POSTGRES_DB: {config.project_name}
    volumes:
      - db_data:/var/lib/postgresql/data
    ports:
      - "5432:5432"

volumes:
  db_data:
"""
    files.append(_write(root / "docker-compose.yml", compose))
    return files


