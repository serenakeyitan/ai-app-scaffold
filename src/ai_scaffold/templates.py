"""Template rendering — generates all project files from config."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from ai_scaffold.scaffold import ScaffoldConfig


def render_all(config: ScaffoldConfig, project_dir: Path) -> list[Path]:
    """Render all project files and return list of created paths."""
    files: list[Path] = []

    renderers = [
        _render_env_example,
        _render_gitignore,
        _render_readme,
        _render_backend,
        _render_pyproject,
    ]

    if config.docker:
        renderers.append(_render_docker)

    if config.ci:
        renderers.append(_render_ci)

    if config.monitoring:
        renderers.append(_render_monitoring)

    for renderer in renderers:
        created = renderer(config, project_dir)
        files.extend(created)

    return files


