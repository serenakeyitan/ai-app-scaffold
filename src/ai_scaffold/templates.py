def _write(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


def _render_env_example(config: ScaffoldConfig, root: Path) -> list[Path]:
    lines = ["# Auto-generated by ai-scaffold", "# Copy to .env and fill in your values", ""]
    lines.append("# App")
    lines.append("APP_ENV=development")
    lines.append("SECRET_KEY=change-me-in-production")
    lines.append("ALLOWED_ORIGINS=http://localhost:3000")
    lines.append("")

    # AI
    lines.append(f"# AI — {config.ai_provider}")
    for var in config.ai_info.get("env_vars", []):
        lines.append(f"{var}=")
    lines.append(f"AI_MODEL={config.ai_info.get('model_default', '')}")
    lines.append("")

    # Auth
    lines.append(f"# Auth — {config.auth_provider}")
    for var in config.auth_info.get("env_vars", []):
        lines.append(f"{var}=")
    lines.append("")

    # DB
    lines.append(f"# Database — {config.db_provider}")
    for var in config.db_info.get("env_vars", []):
        lines.append(f"{var}=")
    lines.append("")

    # Payments
    if config.payment_provider != "none":
        lines.append(f"# Payments — {config.payment_provider}")
        for var in config.payment_info.get("env_vars", []):
            lines.append(f"{var}=")
        lines.append("")

    # Monitoring
    if config.monitoring:
        lines.append("# Monitoring")
        lines.append("SENTRY_DSN=")
        lines.append("")

    return [_write(root / ".env.example", "\n".join(lines))]


